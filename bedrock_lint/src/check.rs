//! What a check is: the [`Check`] trait, its [`CheckMeta`] (catalogue id and the data it needs) and the static
//! registry every check file adds itself to with `inventory::submit!`. Severity and title come from the catalogue,
//! so a check can't disagree with the book.

use crate::config::Config;
use crate::finding::Finding;
use crate::model::Firmware;

/// A piece of the firmware model a check needs; without it the check is reported as not run, with the reason
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Need {
    /// Parsed Rust source (`src/`)
    Sources,
    /// `build.rs`
    BuildScript,
    /// `memory.x`
    MemoryX,
    /// `bedrock_fw.json`
    BedrockFw,
    /// The chip, from `bedrock_fw.json`
    Chip,
    /// The linked ELF (`--elf`)
    Elf,
    /// Arm Thumb code in the ELF: frames and calls are read from it
    Thumb,
    /// `memory.x` with a `MEMORY` block that could be read
    Regions,
}

impl Need {
    /// A short name (`build-script`)
    pub fn name(self) -> &'static str {
        match self {
            Need::Sources => "sources",
            Need::BuildScript => "build-script",
            Need::MemoryX => "memory-x",
            Need::BedrockFw => "bedrock-fw",
            Need::Chip => "chip",
            Need::Elf => "elf",
            Need::Thumb => "thumb-code",
            Need::Regions => "memory-regions",
        }
    }

    /// `None` when the firmware has it, else why not and what would provide it
    pub fn missing(self, fw: &Firmware) -> Option<String> {
        let missing = match self {
            Need::Sources => fw.sources.is_empty(),
            Need::BuildScript => fw.build_script.is_none(),
            Need::MemoryX => fw.memory_x.is_none(),
            Need::BedrockFw => fw.bedrock_fw.is_none(),
            Need::Chip => fw.chip().is_none(),
            Need::Elf => fw.elf.is_none(),
            Need::Thumb => fw.elf.as_ref().is_none_or(|e| e.code.is_empty()),
            Need::Regions => fw.memory.is_empty(),
        };
        missing.then(|| {
            match self {
                Need::Sources => "no Rust source could be parsed under src/",
                Need::BuildScript => "the crate has no build script",
                Need::MemoryX => "the crate has no memory.x",
                Need::BedrockFw => {
                    "no bedrock_fw.json: the firmware was not generated by the template"
                }
                Need::Chip => "bedrock_fw.json names no chip (answers.chip)",
                Need::Elf => "no ELF given: pass --elf target/<triple>/release/<name>",
                Need::Thumb => {
                    "no Arm Thumb functions in the ELF (or no ELF): frames and calls are read from Thumb code only"
                }
                Need::Regions => "no MEMORY regions: memory.x is missing or could not be read",
            }
            .to_string()
        })
    }
}

/// What the registry knows about a check
#[derive(Debug)]
pub struct CheckMeta {
    /// The catalogue id (`EXE-3`)
    pub id: &'static str,
    pub needs: &'static [Need],
}

/// One automatic check of the catalogue
pub trait Check: Sync {
    fn meta(&self) -> &'static CheckMeta;
    /// The findings on the firmware; called only when every need is there
    fn run(&self, fw: &Firmware) -> Vec<Finding> {
        let _ = fw;
        Vec::new()
    }

    /// The findings with the project's `bedrock-lint.toml` at hand (the thresholds in `limits`); a check that
    /// measures something implements this instead of [`Check::run`]
    fn run_with(&self, fw: &Firmware, cfg: &Config) -> Vec<Finding> {
        let _ = cfg;
        self.run(fw)
    }
}

/// A check in the static registry; each check file submits one
pub struct Registered(pub &'static dyn Check);

inventory::collect!(Registered);

/// Every registered check, in catalogue order
pub fn registered() -> Vec<&'static dyn Check> {
    let mut checks: Vec<&'static dyn Check> = inventory::iter::<Registered>
        .into_iter()
        .map(|r| r.0)
        .collect();
    checks.sort_by_key(|c| crate::catalogue::order_key(c.meta().id));
    checks
}

/// The registered check with this id
pub fn check(id: &str) -> Option<&'static dyn Check> {
    inventory::iter::<Registered>
        .into_iter()
        .map(|r| r.0)
        .find(|c| c.meta().id.eq_ignore_ascii_case(id))
}
