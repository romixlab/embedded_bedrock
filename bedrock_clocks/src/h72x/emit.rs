//! Writes `clocks.rs`: one const per register with its fields spelled out, the exact frequencies with their units,
//! the FRACN steer ranges, and the `PLAN` that `bedrock_clocks_rt::h72x::apply` writes.

use std::fmt::Write as _;

use exact_units::prefix::One;
use exact_units::units::Hertz;
use exact_units::{Exact, Rounding};

use super::check::fracn_span;
use super::config::{Config, HseMode, Ker, Periph, PllSource, Supply, SysSource, Vos};
use super::regs::Regs;
use super::tree::Tree;

/// Where the config came from, for the generated header.
pub struct Origin<'a> {
    /// As the user names it on the command line: `boards/b135b/clocks.toml`.
    pub path: &'a str,
    /// [source_hash](crate::source_hash) of the file's bytes.
    pub hash: u64,
}

fn hex(v: u32) -> String {
    format!("0x{:04X}_{:04X}", v >> 16, v & 0xFFFF)
}

/// `Fixed<Hertz, Rational<1, D>, u64>` const for an exact frequency: D is its denominator in lowest terms, so the
/// `Fixed` holds it exactly.
fn fixed(name: &str, h: Exact<Hertz>, doc: &str, out: &mut String) {
    let r = h.get();
    let floor = h
        .to_rounded::<One, u32>(Rounding::Floor)
        .expect("a clock fits u32 Hz");
    let _ = writeln!(out, "/// {doc}: {h}");
    let _ = writeln!(
        out,
        "pub const {name}: Fixed<Hertz, Rational<1, {}>, u64> = Fixed::new({});",
        r.denom().expect("a clock's denominator fits u128"),
        r.numer().expect("a clock fits u128 Hz")
    );
    let _ = writeln!(
        out,
        "/// {doc}, rounded down to whole Hz (lossy, for drivers that take integer Hz)"
    );
    let _ = writeln!(out, "pub const {name}_HZ_FLOOR: u32 = {};", floor.get());
}

fn supply_text(s: Supply) -> &'static str {
    match s {
        Supply::Default => "configuration 0, LDO supplies VCORE, SMPS on",
        Supply::Ldo => "configuration 1, LDO, SMPS off",
        Supply::DirectSmps => "configuration 2, direct SMPS, LDO bypassed",
        Supply::SmpsLdo(_) => "configuration 3, SMPS supplies the LDO",
        Supply::SmpsExternalLdo(_) => "configuration 4, SMPS supplies external and the LDO",
        Supply::SmpsExternalBypass(_) => "configuration 5, SMPS supplies external, LDO bypassed",
        Supply::Bypass => "configuration 6, external VCORE, LDO bypassed",
    }
}

fn ker(k: Ker) -> &'static str {
    match k {
        Ker::Pll1Q => "pll1_q_ck",
        Ker::Pll2P => "pll2_p_ck",
        Ker::Pll2Q => "pll2_q_ck",
        Ker::Pll2R => "pll2_r_ck",
        Ker::Pll3P => "pll3_p_ck",
        Ker::Pll3Q => "pll3_q_ck",
        Ker::Pll3R => "pll3_r_ck",
        Ker::Hse => "hse_ck",
        Ker::HsiKer => "hsi_ker_ck",
        Ker::CsiKer => "csi_ker_ck",
        Ker::Hsi48 => "hsi48_ck",
        Ker::Lse => "lse_ck",
        Ker::PerCk => "per_ck",
        Ker::Bus => "bus clock",
        Ker::Disabled => "off",
    }
}

fn periph_const(p: Periph) -> &'static str {
    match p {
        Periph::Sdmmc => "SDMMC_KER_CK",
        Periph::Octospi => "OCTOSPI_KER_CK",
        Periph::Fmc => "FMC_KER_CK",
        Periph::Fdcan => "FDCAN_KER_CK",
        Periph::Spi45 => "SPI45_KER_CK",
        Periph::Spi123 => "SPI123_KER_CK",
        Periph::UsbOtgHs => "USB_KER_CK",
        Periph::I2c1235 => "I2C1235_KER_CK",
        Periph::Usart16910 => "USART16910_KER_CK",
        Periph::Usart234578 => "USART234578_KER_CK",
        Periph::Spi6 => "SPI6_KER_CK",
        Periph::Adc => "ADC_KER_CK",
        Periph::I2c4 => "I2C4_KER_CK",
        Periph::Lpuart1 => "LPUART1_KER_CK",
    }
}

/// The whole file. `cfg` must have passed [check](super::check::check) without errors.
pub fn emit(cfg: &Config, t: &Tree, r: &Regs, origin: &Origin) -> String {
    let mut o = String::new();
    let v = env!("CARGO_PKG_VERSION");
    let _ = writeln!(
        o,
        "// @generated by bedrock-clocks {v} from {}: do not edit.",
        origin.path
    );
    let _ = writeln!(o, "// Regenerate: bedrock-clocks gen {}", origin.path);
    let _ = writeln!(o, "// source-hash: fnv1a64:{:016x}", origin.hash);
    let _ = writeln!(o, "//");
    let _ = writeln!(
        o,
        "// Clock plan for {}, checked against RM0468 Rev 3, DS13311 Rev 3 and ES0491 Rev 9.",
        cfg.part.name
    );
    let sys = t.sys_ck.expect("checked");
    let from = match cfg.sys.source {
        SysSource::Hsi => "HSI",
        SysSource::Csi => "CSI",
        SysSource::Hse => "HSE",
        SysSource::Pll1P => "PLL1 P",
    };
    let _ = writeln!(
        o,
        "// sys_ck {sys} from {from}, {}, flash {} wait states.",
        format!("{:?}", cfg.vos).to_uppercase(),
        r.flash_acr.latency()
    );
    o.push('\n');
    o.push_str("#![allow(dead_code)]\n\n");
    o.push_str("use bedrock_clocks_rt::exact_units::{Fixed, prefix::Rational, units::Hertz};\n");
    o.push_str("use bedrock_clocks_rt::h72x::{FracnRange, Plan};\n\n");

    // --- registers
    o.push_str("// Registers, in the order apply() writes them.\n\n");
    let _ = writeln!(
        o,
        "/// PWR_CR3 low byte: {} (RM0468 Table 30), written once after POR",
        supply_text(cfg.supply)
    );
    let _ = writeln!(o, "pub const PWR_CR3: u32 = {};", hex(r.pwr_cr3.0));
    let vos_field = match cfg.vos {
        Vos::Vos0 => 0,
        Vos::Vos1 => 3,
        Vos::Vos2 => 2,
        Vos::Vos3 => 1,
    };
    let _ = writeln!(
        o,
        "/// PWR_D3CR VOS={vos_field} ({})",
        format!("{:?}", cfg.vos).to_uppercase()
    );
    let _ = writeln!(
        o,
        "pub const PWR_D3CR_VOS: u32 = {};",
        hex(r.pwr_d3cr_vos.0)
    );

    let mut osc = Vec::new();
    if let Some(d) = cfg.hsi_div {
        osc.push(format!("HSION HSIDIV=÷{}", d.ratio()));
    }
    if cfg.csi {
        osc.push("CSION".into());
    }
    if cfg.hsi48 {
        osc.push("HSI48ON".into());
    }
    if let Some(h) = cfg.hse {
        osc.push(format!(
            "HSEON{} ({})",
            if h.mode == HseMode::Bypass {
                " HSEBYP"
            } else {
                ""
            },
            h.freq
        ));
    }
    let _ = writeln!(o, "/// RCC_CR oscillators: {}", osc.join(" "));
    let _ = writeln!(o, "pub const RCC_CR_OSC: u32 = {};", hex(r.rcc_cr_osc.0));
    let src = match cfg.pll_source {
        PllSource::Hsi => "HSI",
        PllSource::Csi => "CSI",
        PllSource::Hse => "HSE",
    };
    let ms: Vec<String> = cfg
        .pll
        .iter()
        .enumerate()
        .map(|(i, p)| format!("DIVM{}={}", i + 1, p.map_or(0, |p| p.m.get())))
        .collect();
    let _ = writeln!(o, "/// RCC_PLLCKSELR: PLLSRC={src} {}", ms.join(" "));
    let _ = writeln!(o, "pub const RCC_PLLCKSELR: u32 = {};", hex(r.pllckselr.0));

    let mut cfgr_fields = Vec::new();
    for (i, p) in cfg.pll.iter().enumerate() {
        let n = i + 1;
        let Some(p) = p else {
            cfgr_fields.push(format!("PLL{n} off"));
            continue;
        };
        let po = t.pll[i].expect("checked");
        let en: Vec<&str> = [("P", p.p), ("Q", p.q), ("R", p.r)]
            .iter()
            .filter(|(_, v)| v.is_some())
            .map(|(n, _)| *n)
            .collect();
        cfgr_fields.push(format!(
            "PLL{n} FRACEN={} VCOSEL={} RGE={} DIV{}EN",
            p.fracn.is_some() as u8,
            if po.wide { "wide" } else { "medium" },
            po.rge.to_bits(),
            en.join("/")
        ));
    }
    let _ = writeln!(o, "/// RCC_PLLCFGR: {}", cfgr_fields.join(", "));
    let _ = writeln!(o, "pub const RCC_PLLCFGR: u32 = {};", hex(r.pllcfgr.0));

    for (i, p) in cfg.pll.iter().enumerate() {
        let n = i + 1;
        let Some(p) = p else { continue };
        let po = t.pll[i].expect("checked");
        let input = t.pll_in.expect("checked");
        let frac = p
            .fracn
            .map(|f| format!(" + FRACN {}/8192", f.get()))
            .unwrap_or_default();
        let _ = writeln!(o);
        let _ = writeln!(
            o,
            "/// PLL{n}: {src} {input} ÷ M {} = ref {} (RGE {}), {} VCO × (N {}{frac}) = VCO {}",
            p.m.get(),
            po.ref_ck,
            po.rge.to_bits(),
            if po.wide { "wide" } else { "medium" },
            p.n.get(),
            po.vco
        );
        let outs: Vec<String> = [("P", p.p, po.p), ("Q", p.q, po.q), ("R", p.r, po.r)]
            .iter()
            .filter_map(|(name, d, f)| Some(format!("{name} ÷{} = {}", (*d)?.get(), (*f)?)))
            .collect();
        let _ = writeln!(o, "/// {}", outs.join(", "));
        let fields: Vec<String> = [("DIVR", p.r), ("DIVQ", p.q), ("DIVP", p.p)]
            .iter()
            .map(|(name, d)| match d {
                Some(d) => format!("{name}{n}={} (÷{})", d.get() - 1, d.get()),
                None => format!("{name}{n}=0 (off)"),
            })
            .collect();
        let _ = writeln!(
            o,
            "pub const RCC_PLL{n}DIVR: u32 = {}; // {} DIVN{n}={} (×{})",
            hex(r.plldivr[i].0),
            fields.join(" "),
            p.n.get() - 1,
            p.n.get()
        );
        let _ = writeln!(
            o,
            "pub const RCC_PLL{n}FRACR: u32 = {}; // FRACN{n}={}",
            hex(r.pllfracr[i].0),
            p.fracn.map_or(0, |f| f.get())
        );
    }
    o.push('\n');

    let s = &cfg.sys;
    let _ = writeln!(
        o,
        "/// FLASH_ACR: LATENCY={} WRHIGHFREQ={} for AXI {} at {} (RM0468 Table 16)",
        r.flash_acr.latency(),
        r.flash_acr.wrhighfreq(),
        t.hclk.expect("checked"),
        format!("{:?}", cfg.vos).to_uppercase()
    );
    let _ = writeln!(o, "pub const FLASH_ACR: u32 = {};", hex(r.flash_acr.0));
    let _ = writeln!(
        o,
        "/// RCC_D1CFGR: D1CPRE ÷{} HPRE ÷{} D1PPRE ÷{}",
        s.d1cpre.ratio(),
        s.hpre.ratio(),
        s.d1ppre.ratio()
    );
    let _ = writeln!(o, "pub const RCC_D1CFGR: u32 = {};", hex(r.d1cfgr.0));
    let _ = writeln!(
        o,
        "/// RCC_D2CFGR: D2PPRE1 ÷{} D2PPRE2 ÷{}",
        s.d2ppre1.ratio(),
        s.d2ppre2.ratio()
    );
    let _ = writeln!(o, "pub const RCC_D2CFGR: u32 = {};", hex(r.d2cfgr.0));
    let _ = writeln!(o, "/// RCC_D3CFGR: D3PPRE ÷{}", s.d3ppre.ratio());
    let _ = writeln!(o, "pub const RCC_D3CFGR: u32 = {};", hex(r.d3cfgr.0));
    let sw = match s.source {
        SysSource::Hsi => "HSI",
        SysSource::Csi => "CSI",
        SysSource::Hse => "HSE",
        SysSource::Pll1P => "PLL1 P",
    };
    let _ = writeln!(o, "/// RCC_CFGR: SW={sw} TIMPRE={}", s.timpre as u8);
    let _ = writeln!(o, "pub const RCC_CFGR: u32 = {};", hex(r.cfgr.0));

    let k = &cfg.kernel;
    let _ = writeln!(
        o,
        "/// RCC_D1CCIPR: CKPERSEL={} SDMMCSEL={} OCTOSPISEL={} FMCSEL={}",
        ker(k.per_ck),
        ker(k.sdmmc),
        ker(k.octospi),
        ker(k.fmc)
    );
    let _ = writeln!(o, "pub const RCC_D1CCIPR: u32 = {};", hex(r.d1ccipr.0));
    let _ = writeln!(
        o,
        "/// RCC_D2CCIP1R: FDCANSEL={} SPI45SEL={} SPI123SEL={}",
        ker(k.fdcan),
        ker(k.spi45),
        ker(k.spi123)
    );
    let _ = writeln!(o, "pub const RCC_D2CCIP1R: u32 = {};", hex(r.d2ccip1r.0));
    let _ = writeln!(
        o,
        "/// RCC_D2CCIP2R: USBSEL={} I2C1235SEL={} USART16910SEL={} USART234578SEL={}",
        ker(k.usb),
        ker(k.i2c1235),
        ker(k.usart16910),
        ker(k.usart234578)
    );
    let _ = writeln!(o, "pub const RCC_D2CCIP2R: u32 = {};", hex(r.d2ccip2r.0));
    let _ = writeln!(
        o,
        "/// RCC_D3CCIPR: SPI6SEL={} ADCSEL={} I2C4SEL={} LPUART1SEL={}",
        ker(k.spi6),
        ker(k.adc),
        ker(k.i2c4),
        ker(k.lpuart1)
    );
    let _ = writeln!(o, "pub const RCC_D3CCIPR: u32 = {};", hex(r.d3ccipr.0));
    let off = if r.rcc_cr_off.hsion() {
        "HSION"
    } else {
        "none"
    };
    let _ = writeln!(
        o,
        "/// RCC_CR bits cleared at the end (oscillators not used): {off}"
    );
    let _ = writeln!(o, "pub const RCC_CR_OFF: u32 = {};", hex(r.rcc_cr_off.0));
    o.push('\n');

    o.push_str("/// What `bedrock_clocks_rt::h72x::apply` writes.\n");
    o.push_str("pub const PLAN: Plan = Plan {\n");
    let pll_on: Vec<String> = (0..3)
        .filter(|&i| r.rcc_cr_pll_on.pllon(i))
        .map(|i| format!("PLL{}ON", i + 1))
        .collect();
    for (field, value) in [
        ("pwr_cr3", "PWR_CR3".to_string()),
        ("pwr_d3cr_vos", "PWR_D3CR_VOS".into()),
        ("flash_acr", "FLASH_ACR".into()),
        ("rcc_cr_osc", "RCC_CR_OSC".into()),
        (
            "rcc_cr_pll_on",
            format!("{}, // {}", hex(r.rcc_cr_pll_on.0), pll_on.join(" ")),
        ),
        ("rcc_cr_off", "RCC_CR_OFF".into()),
        ("pllckselr", "RCC_PLLCKSELR".into()),
        ("pllcfgr", "RCC_PLLCFGR".into()),
    ] {
        if value.contains("//") {
            let _ = writeln!(o, "    {field}: {value}");
        } else {
            let _ = writeln!(o, "    {field}: {value},");
        }
    }
    let regs3 = |name: &str, f: &dyn Fn(usize) -> u32| -> String {
        (0..3)
            .map(|i| {
                if cfg.pll[i].is_some() {
                    format!("RCC_PLL{}{name}", i + 1)
                } else {
                    hex(f(i))
                }
            })
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = writeln!(o, "    plldivr: [{}],", regs3("DIVR", &|i| r.plldivr[i].0));
    let _ = writeln!(
        o,
        "    pllfracr: [{}],",
        regs3("FRACR", &|i| r.pllfracr[i].0)
    );
    for (field, value) in [
        ("cfgr", "RCC_CFGR"),
        ("d1cfgr", "RCC_D1CFGR"),
        ("d2cfgr", "RCC_D2CFGR"),
        ("d3cfgr", "RCC_D3CFGR"),
        ("d1ccipr", "RCC_D1CCIPR"),
        ("d2ccip1r", "RCC_D2CCIP1R"),
        ("d2ccip2r", "RCC_D2CCIP2R"),
        ("d3ccipr", "RCC_D3CCIPR"),
    ] {
        let _ = writeln!(o, "    {field}: {value},");
    }
    o.push_str("};\n\n");

    // --- frequencies
    o.push_str("// Exact frequencies.\n\n");
    fixed("SYS_CK", sys, "sys_ck", &mut o);
    for (name, f, doc) in [
        ("CPU_CK", t.cpu, "Cortex-M7 clock (after D1CPRE)"),
        ("HCLK", t.hclk, "AXI / AHB clock rcc_hclk1..4, rcc_aclk"),
        ("PCLK1", t.pclk1, "APB1"),
        ("PCLK2", t.pclk2, "APB2"),
        ("PCLK3", t.pclk3, "APB3"),
        ("PCLK4", t.pclk4, "APB4"),
        (
            "TIM_APB1_KER_CK",
            t.tim_apb1,
            "APB1 timers (TIM2..7, 12..14, 23, 24)",
        ),
        (
            "TIM_APB2_KER_CK",
            t.tim_apb2,
            "APB2 timers (TIM1, 8, 15..17)",
        ),
    ] {
        if let Some(f) = f {
            fixed(name, f, doc, &mut o);
        }
    }
    for (i, po) in t.pll.iter().enumerate() {
        let Some(po) = po else { continue };
        for (out, f) in [("P", po.p), ("Q", po.q), ("R", po.r)] {
            if let Some(f) = f {
                fixed(
                    &format!("PLL{}_{out}_CK", i + 1),
                    f,
                    &format!("pll{}_{}_ck", i + 1, out.to_lowercase()),
                    &mut o,
                );
            }
        }
    }
    for &p in &cfg.used {
        if let Some(Some(f)) = t.kernel.get(&p) {
            let target = cfg.expect.iter().find(|e| e.periph == p);
            let mut doc = format!("{p:?} kernel clock");
            if let Some(e) = target {
                let err = error_text(*f, e.freq);
                let _ = write!(doc, " (target {}, {err})", e.freq);
            }
            fixed(periph_const(p), *f, &doc, &mut o);
        }
    }

    // --- FRACN steering
    let mut any = false;
    for (i, p) in cfg.pll.iter().enumerate() {
        let Some(p) = p else { continue };
        let Some(f) = p.fracn else { continue };
        let po = t.pll[i].expect("checked");
        if !any {
            o.push_str(
                "\n// FRACN steering ranges (RM0468 §8.5.5: FRACEN 0, write FRACN, FRACEN 1).\n\n",
            );
            any = true;
        }
        let f = f.get();
        let (min, max) = match fracn_span(p) {
            // the checker held both ends to 1..=8191
            Some((lo, hi)) => (lo as u16, hi as u16),
            None => (f, f),
        };
        let step = (po.ref_ck / 8192).expect("small");
        // FRACEN low for 2 ref_ck periods, counted in PLLCFGR reads of at least one hclk cycle each (RCC-10)
        let hclk = t.hclk.expect("checked");
        let hold = ((hclk * 2).expect("small") / po.ref_ck)
            .and_then(|r| r.as_ratio().to_rounded::<One, u32>(Rounding::Ceil))
            .expect("small")
            .get()
            + 1;
        let _ = writeln!(
            o,
            "/// PLL{}: {} of VCO per FRACN step; steer range {}",
            i + 1,
            step,
            match p.steer {
                Some(s) => format!("{:+}..={:+} ppm", s.min.get(), s.max.get()),
                None => "none (fixed FRACN)".into(),
            }
        );
        let _ = writeln!(
            o,
            "pub const PLL{}_FRACN: FracnRange = FracnRange {{\n    pll: {},\n    n: {},\n    nominal: {f},\n    min: {min},\n    max: {max},\n    vco_step_hz_num: {},\n    vco_step_hz_den: {},\n    latch_hold_reads: {hold},\n}};",
            i + 1,
            i + 1,
            p.n.get(),
            step.get().numer().expect("a VCO step fits u128 Hz"),
            step.get()
                .denom()
                .expect("a VCO step's denominator fits u128")
        );
    }
    o
}

/// Signed error of `f` against `target`, exactly: `-0.244140625 ppm`, or `exact`.
pub fn error_text(f: Exact<Hertz>, target: Exact<Hertz>) -> String {
    match f.rel_error(target) {
        Some(e) if e.is_zero() => "exact".into(),
        Some(e) => e.to_string(),
        None => "error too large to show".into(),
    }
}
