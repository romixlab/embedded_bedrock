//! Writes `clocks.rs`: one const per register with its fields spelled out, the exact frequencies with their units,
//! and the `PLAN` that `bedrock_clocks_rt::g0::apply` writes.

use std::fmt::Write as _;

pub use crate::text::error_text;
use crate::text::{fixed, hex};

use super::config::{Config, HseMode, Ker, Periph, PllSource, SysSource, Vos};
use super::regs::Regs;
use super::tree::Tree;

/// Where the config came from, for the generated header.
pub struct Origin<'a> {
    /// As the user names it on the command line: `fw/donguru/clocks.toml`.
    pub path: &'a str,
    /// [source_hash](crate::source_hash) of the file's bytes.
    pub hash: u64,
}

fn ker(k: Ker) -> &'static str {
    match k {
        Ker::Sysclk => "SYSCLK",
        Ker::Pclk => "PCLK",
        Ker::Timpclk => "TIMPCLK",
        Ker::Hsi16 => "HSI16",
        Ker::Hsi16Div8 => "HSI16/8",
        Ker::Hsi48 => "HSI48",
        Ker::Hse => "HSE",
        Ker::Lsi => "LSI",
        Ker::Lse => "LSE",
        Ker::PllP => "PLLPCLK",
        Ker::PllQ => "PLLQCLK",
        Ker::I2sCkin => "I2S_CKIN",
        Ker::Disabled => "off",
    }
}

fn periph_const(p: Periph) -> &'static str {
    match p {
        Periph::Adc => "ADC_KER_CK",
        Periph::Rng => "RNG_KER_CK",
        Periph::Tim15 => "TIM15_KER_CK",
        Periph::Tim1 => "TIM1_KER_CK",
        Periph::Lptim2 => "LPTIM2_KER_CK",
        Periph::Lptim1 => "LPTIM1_KER_CK",
        Periph::I2c2 => "I2C2_KER_CK",
        Periph::I2c1 => "I2C1_KER_CK",
        Periph::Lpuart1 => "LPUART1_KER_CK",
        Periph::Lpuart2 => "LPUART2_KER_CK",
        Periph::Usart3 => "USART3_KER_CK",
        Periph::Usart2 => "USART2_KER_CK",
        Periph::Usart1 => "USART1_KER_CK",
        Periph::Usb => "USB_KER_CK",
        Periph::Fdcan => "FDCAN_KER_CK",
        Periph::I2s2 => "I2S2_KER_CK",
        Periph::I2s1 => "I2S1_KER_CK",
        Periph::Ucpd => "UCPD_KER_CK",
    }
}

fn range(v: Vos) -> &'static str {
    match v {
        Vos::Range1 => "Range 1",
        Vos::Range2 => "Range 2",
    }
}

/// The whole file. `cfg` must have passed [check](super::check::check) without errors.
pub fn emit(cfg: &Config, t: &Tree, r: &Regs, origin: &Origin) -> String {
    let mut o = String::new();
    let v = env!("CARGO_PKG_VERSION");
    let _ = writeln!(
        o,
        "// @generated by bedrock-clocks {v} from {}: do not edit.",
        origin.path
    );
    let _ = writeln!(o, "// Regenerate: bedrock-clocks gen {}", origin.path);
    let _ = writeln!(o, "// source-hash: fnv1a64:{:016x}", origin.hash);
    let _ = writeln!(o, "//");
    let _ = writeln!(
        o,
        "// Clock plan for {}, checked against RM0444 Rev 5, DS13560 Rev 6 and ES0548 Rev 4.",
        cfg.part.name
    );
    let sys = t.sysclk.expect("checked");
    let from = match cfg.sys.source {
        SysSource::Hsisys => "HSISYS",
        SysSource::Hse => "HSE",
        SysSource::PllR => "PLLRCLK",
    };
    let ws = r.flash_acr & 0b111;
    let _ = writeln!(
        o,
        "// SYSCLK {sys} from {from}, {}, flash {ws} wait states.",
        range(cfg.vos)
    );
    o.push('\n');
    o.push_str("#![allow(dead_code)]\n\n");
    o.push_str("use bedrock_clocks_rt::exact_units::{Fixed, prefix::Rational, units::Hertz};\n");
    o.push_str("use bedrock_clocks_rt::g0::Plan;\n\n");

    // --- registers
    o.push_str("// Registers, in the order apply() writes them.\n\n");
    let _ = writeln!(
        o,
        "/// PWR_CR1 VOS={} ({})",
        r.pwr_cr1_vos >> 9,
        range(cfg.vos)
    );
    let _ = writeln!(o, "pub const PWR_CR1_VOS: u32 = {};", hex(r.pwr_cr1_vos));

    let mut osc = Vec::new();
    if let Some(d) = cfg.hsi16 {
        osc.push(format!("HSION HSIDIV=÷{}", d.ratio()));
    }
    if let Some(h) = cfg.hse {
        osc.push(format!(
            "HSEON{} ({})",
            if h.mode == HseMode::Bypass {
                " HSEBYP"
            } else {
                ""
            },
            h.freq
        ));
    }
    if cfg.hsi48.is_some() {
        osc.push("HSI48ON".into());
    }
    let _ = writeln!(o, "/// RCC_CR oscillators: {}", osc.join(" "));
    let _ = writeln!(o, "pub const RCC_CR_OSC: u32 = {};", hex(r.rcc_cr_osc));

    match (cfg.pll, t.pll) {
        (Some(p), Some(po)) => {
            let src = match p.source {
                PllSource::Hsi16 => "HSI16",
                PllSource::Hse => "HSE",
            };
            let outs: Vec<String> = [
                ("P", p.p.map(|d| d.get()), po.p),
                ("Q", p.q.map(|d| d.get()), po.q),
                ("R", p.r.map(|d| d.get()), po.r),
            ]
            .iter()
            .filter_map(|(name, d, f)| Some(format!("{name} ÷{} = {}", (*d)?, (*f)?)))
            .collect();
            let _ = writeln!(
                o,
                "/// RCC_PLLCFGR: {src} ÷ M {} = {} × N {} = VCO {}; {}",
                p.m.get(),
                po.input,
                p.n.get(),
                po.vco,
                outs.join(", ")
            );
        }
        _ => {
            let _ = writeln!(o, "/// RCC_PLLCFGR: PLL off");
        }
    }
    let _ = writeln!(o, "pub const RCC_PLLCFGR: u32 = {};", hex(r.pllcfgr));
    let _ = writeln!(
        o,
        "/// FLASH_ACR: LATENCY={ws} for HCLK {} in {} (RM0444 Table 12), PRFTEN={} ICEN={}",
        t.hclk.expect("checked"),
        range(cfg.vos),
        cfg.prefetch as u8,
        cfg.icache as u8
    );
    let _ = writeln!(o, "pub const FLASH_ACR: u32 = {};", hex(r.flash_acr));
    let s = &cfg.sys;
    let _ = writeln!(
        o,
        "/// RCC_CFGR: SW={from} HPRE ÷{} PPRE ÷{}",
        s.hpre.ratio(),
        s.ppre.ratio()
    );
    let _ = writeln!(o, "pub const RCC_CFGR: u32 = {};", hex(r.cfgr));

    let k = &cfg.kernel;
    let _ = writeln!(
        o,
        "/// RCC_CCIPR: ADCSEL={} RNGSEL={} ÷{} TIM1SEL={} TIM15SEL={} LPTIM1SEL={} LPTIM2SEL={} I2C1SEL={} I2C2SEL={}",
        ker(k.adc),
        ker(k.rng),
        k.rng_div,
        ker(k.tim1),
        ker(k.tim15),
        ker(k.lptim1),
        ker(k.lptim2),
        ker(k.i2c1),
        ker(k.i2c2)
    );
    let _ = writeln!(
        o,
        "/// USART1SEL={} USART2SEL={} USART3SEL={} LPUART1SEL={} LPUART2SEL={}",
        ker(k.usart1),
        ker(k.usart2),
        ker(k.usart3),
        ker(k.lpuart1),
        ker(k.lpuart2)
    );
    let _ = writeln!(o, "pub const RCC_CCIPR: u32 = {};", hex(r.ccipr));
    let _ = writeln!(
        o,
        "/// RCC_CCIPR2: USBSEL={} FDCANSEL={} I2S1SEL={} I2S2SEL={}",
        ker(k.usb),
        ker(k.fdcan),
        ker(k.i2s1),
        ker(k.i2s2)
    );
    let _ = writeln!(o, "pub const RCC_CCIPR2: u32 = {};", hex(r.ccipr2));
    if r.crs_cr != 0 {
        let reload = r.crs_cfgr & 0xFFFF;
        let felim = (r.crs_cfgr >> 16) & 0xFF;
        let _ = writeln!(
            o,
            "/// CRS_CFGR: SYNCSRC=USB SOF, RELOAD={reload} (48 MHz / 1 kHz − 1), FELIM={felim} (RM0444 §6.4.3-6.4.4)"
        );
    } else {
        let _ = writeln!(o, "/// CRS_CFGR: CRS not used");
    }
    let _ = writeln!(o, "pub const CRS_CFGR: u32 = {};", hex(r.crs_cfgr));
    let crs = if r.crs_cr != 0 {
        "AUTOTRIMEN CEN, TRIM=64"
    } else {
        "CRS not used"
    };
    let _ = writeln!(o, "/// CRS_CR: {crs}");
    let _ = writeln!(o, "pub const CRS_CR: u32 = {};", hex(r.crs_cr));
    let off = if r.rcc_cr_off != 0 { "HSION" } else { "none" };
    let _ = writeln!(
        o,
        "/// RCC_CR bits cleared at the end (oscillators not used): {off}"
    );
    let _ = writeln!(o, "pub const RCC_CR_OFF: u32 = {};", hex(r.rcc_cr_off));
    o.push('\n');

    o.push_str("/// What `bedrock_clocks_rt::g0::apply` writes.\n");
    o.push_str("pub const PLAN: Plan = Plan {\n");
    let pll_on = if r.rcc_cr_pll_on != 0 {
        "PLLON"
    } else {
        "PLL off"
    };
    let _ = writeln!(o, "    pwr_cr1_vos: PWR_CR1_VOS,");
    let _ = writeln!(o, "    flash_acr: FLASH_ACR,");
    let _ = writeln!(o, "    rcc_cr_osc: RCC_CR_OSC,");
    let _ = writeln!(
        o,
        "    rcc_cr_pll_on: {}, // {pll_on}",
        hex(r.rcc_cr_pll_on)
    );
    let _ = writeln!(o, "    rcc_cr_off: RCC_CR_OFF,");
    for (field, value) in [
        ("pllcfgr", "RCC_PLLCFGR"),
        ("cfgr", "RCC_CFGR"),
        ("ccipr", "RCC_CCIPR"),
        ("ccipr2", "RCC_CCIPR2"),
        ("crs_cfgr", "CRS_CFGR"),
        ("crs_cr", "CRS_CR"),
    ] {
        let _ = writeln!(o, "    {field}: {value},");
    }
    o.push_str("};\n\n");

    // --- frequencies
    o.push_str("// Exact frequencies.\n\n");
    fixed("SYSCLK", sys, "SYSCLK", &mut o);
    for (name, f, doc) in [
        ("HCLK", t.hclk, "HCLK: AHB, the core and memory"),
        ("PCLK", t.pclk, "PCLK: APB"),
        ("TIMPCLK", t.timpclk, "TIMPCLK: the timers"),
        ("HSI16", t.hsi16, "HSI16"),
        ("HSI48", t.hsi48, "HSI48 (trimmed by the CRS)"),
    ] {
        if let Some(f) = f {
            fixed(name, f, doc, &mut o);
        }
    }
    if let Some(po) = t.pll {
        for (out, f) in [("P", po.p), ("Q", po.q), ("R", po.r)] {
            if let Some(f) = f {
                fixed(&format!("PLL{out}CLK"), f, &format!("PLL{out}CLK"), &mut o);
            }
        }
    }
    for &p in &cfg.used {
        if let Some(Some(f)) = t.kernel.get(&p) {
            let target = cfg.expect.iter().find(|e| e.periph == p);
            let mut doc = format!("{p:?} kernel clock");
            if let Some(e) = target {
                let err = error_text(*f, e.freq);
                let _ = write!(doc, " (target {}, {err})", e.freq);
            }
            fixed(periph_const(p), *f, &doc, &mut o);
        }
    }
    o
}
